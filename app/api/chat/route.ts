export async function POST(req: NextRequest) {
  const ip = getClientIp(req);
  const rl = await checkRateLimit('faq-chat', ip, 30, 60 * 1000);
  if (rl.limited) return NextResponse.json({ error: 'Твърде много заявки. Опитай след малко.' }, { status: 429 });

  try {
    const { messages } = await req.json();

    if (!messages || !Array.isArray(messages)) {
      return NextResponse.json({ error: 'Invalid request' }, { status: 400 });
    }

    const res = await fetch('https://openrouter.ai/api/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${process.env.OPENROUTER_API_KEY}`,
        'Content-Type': 'application/json',
        'HTTP-Referer': 'https://clicka.bg',
      },
      body: JSON.stringify({
        model: 'google/gemini-2.5-flash-lite',
        max_tokens: 400,
        messages: [
          { role: 'system', content: SYSTEM_PROMPT },
          ...messages.slice(-10),
        ],
      }),
    });

    const data = await res.json();
    if (!res.ok || data.error) {
      console.error('OpenRouter error:', JSON.stringify(data));
      return NextResponse.json({ message: 'Нещо се обърка. Опитай пак.' });
    }
    const text = data.choices?.[0]?.message?.content ?? 'Нещо се обърка.';
    return NextResponse.json({ message: text });
  } catch {
    return NextResponse.json({ error: 'Грешка при свързване' }, { status: 500 });
  }
}
